import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

// Format currency in Indian Rupees format (₹)
const formatINR = (val) => {
  const num = Number(val) || 0;
  return 'Rs. ' + num.toLocaleString('en-IN');
};

/**
 * Export Attendance Logs as an official PDF report
 */
export const exportAttendancePDF = ({ data = [], filters = {}, generatedBy = 'Administrator' }) => {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Header background banner
  doc.setFillColor(139, 0, 0); // Velavan Maroon (#8b0000)
  doc.rect(0, 0, pageWidth, 24, 'F');

  // Company Brand
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('VELAVAN PROPERTIES', 14, 11);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text('OFFICIAL ATTENDANCE AUDIT TRAIL & LOGS REPORT', 14, 18);

  // Metadata right-aligned
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric'
  }) + ' ' + now.toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', hour12: true });

  doc.setFontSize(8);
  doc.text(`Generated: ${dateStr}`, pageWidth - 14, 11, { align: 'right' });
  doc.text(`Generated By: ${generatedBy}`, pageWidth - 14, 18, { align: 'right' });

  // Filter Scope Bar
  doc.setFillColor(248, 250, 252); // slate-50
  doc.rect(14, 28, pageWidth - 28, 12, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.rect(14, 28, pageWidth - 28, 12, 'S');

  doc.setTextColor(51, 65, 85);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  const periodText = `Report Scope: ${filters.startDate || 'All Time'} to ${filters.endDate || 'Present'}`;
  const deptText = `Department: ${filters.department || 'All Departments'}`;
  const totalText = `Total Records: ${data.length}`;
  doc.text(`${periodText}   |   ${deptText}   |   ${totalText}`, 18, 35.5);

  // Prepare table data
  const tableRows = data.map((r, idx) => {
    const hours = (r.total_hours !== undefined && r.total_hours !== null) ? Number(r.total_hours).toFixed(1) + ' hrs' : '--';
    const otMins = r.ot_minutes ? `${r.ot_minutes}m` : '--';
    const status = (r.status || 'present').toUpperCase();
    const method = (r.method || 'facelock').toUpperCase();

    return [
      idx + 1,
      r.date || '--',
      r.emp_id || '--',
      r.employee_name || r.name || r.emp_id || '--',
      r.department || 'Operations',
      r.clock_in || '--',
      r.clock_out || '--',
      hours,
      otMins,
      status,
      method
    ];
  });

  autoTable(doc, {
    startY: 44,
    head: [[
      '#',
      'Date',
      'Emp ID',
      'Employee Name',
      'Department',
      'Clock In',
      'Clock Out',
      'Hours',
      'OT',
      'Status',
      'Method'
    ]],
    body: tableRows,
    theme: 'grid',
    styles: {
      fontSize: 8,
      cellPadding: 2.2,
      textColor: [30, 41, 59],
      valign: 'middle'
    },
    headStyles: {
      fillColor: [139, 0, 0],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      halign: 'left'
    },
    columnStyles: {
      0: { halign: 'center', cellWidth: 10 },
      1: { halign: 'center', cellWidth: 22 },
      2: { halign: 'center', cellWidth: 18, fontStyle: 'bold' },
      3: { cellWidth: 42, fontStyle: 'bold' },
      4: { cellWidth: 32 },
      5: { halign: 'center', cellWidth: 20 },
      6: { halign: 'center', cellWidth: 20 },
      7: { halign: 'center', cellWidth: 18 },
      8: { halign: 'center', cellWidth: 16 },
      9: { halign: 'center', cellWidth: 22, fontStyle: 'bold' },
      10: { halign: 'center', cellWidth: 22 }
    },
    didParseCell: (data) => {
      // Highlight Status column
      if (data.section === 'body' && data.column.index === 9) {
        const val = String(data.cell.raw).toLowerCase();
        if (val.includes('present')) {
          data.cell.styles.textColor = [4, 120, 87]; // emerald-700
          data.cell.styles.fontStyle = 'bold';
        } else if (val.includes('late')) {
          data.cell.styles.textColor = [180, 83, 9]; // amber-700
          data.cell.styles.fontStyle = 'bold';
        } else if (val.includes('absent')) {
          data.cell.styles.textColor = [225, 29, 72]; // rose-600
          data.cell.styles.fontStyle = 'bold';
        }
      }
    },
    margin: { left: 14, right: 14 },
    didDrawPage: (data) => {
      // Footer on every page
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.setFont('helvetica', 'normal');
      const footerText = 'Velavan Properties Attendance System • Confidential & Proprietary';
      doc.text(footerText, 14, pageHeight - 8);
      const pageStr = `Page ${data.pageNumber} of ${doc.internal.getNumberOfPages()}`;
      doc.text(pageStr, pageWidth - 14, pageHeight - 8, { align: 'right' });
    }
  });

  const fileDate = filters.startDate ? `${filters.startDate}_to_${filters.endDate || 'now'}` : new Date().toISOString().slice(0, 10);
  doc.save(`Velavan_Attendance_Report_${fileDate}.pdf`);
};

/**
 * Export Monthly Payroll & Full Attendance (+2 Days Extra Salary) as official PDF report
 */
export const exportPayrollPDF = ({ payrollStats = [], filters = {}, generatedBy = 'Administrator' }) => {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Header background banner
  doc.setFillColor(139, 0, 0); // Velavan Maroon (#8b0000)
  doc.rect(0, 0, pageWidth, 26, 'F');

  // Company Brand
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('VELAVAN PROPERTIES', 14, 11);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(254, 240, 138); // Yellow accent
  doc.text('MONTHLY PAYROLL & FULL ATTENDANCE BONUS (+2 DAYS EXTRA SALARY) REPORT', 14, 18);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(241, 245, 249);
  doc.text('Official Policy: 100% Full Attendance (0 Absences) qualifies for an extra 2 days salary bonus + Overtime', 14, 23);

  // Metadata right-aligned
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric'
  }) + ' ' + now.toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', hour12: true });

  doc.setFontSize(8);
  doc.setTextColor(255, 255, 255);
  doc.text(`Generated: ${dateStr}`, pageWidth - 14, 11, { align: 'right' });
  doc.text(`Generated By: ${generatedBy}`, pageWidth - 14, 18, { align: 'right' });

  // Summary Metrics Banner (KPI Boxes)
  const totalPayroll = payrollStats.reduce((sum, p) => sum + (p.netTotalPayout || 0), 0);
  const totalBonus = payrollStats.reduce((sum, p) => sum + (p.fullPresentBonus || 0), 0);
  const totalQualified = payrollStats.filter(p => p.isFullPresentEligible).length;
  const totalOt = payrollStats.reduce((sum, p) => sum + (p.otPay || 0), 0);

  const boxWidth = (pageWidth - 28 - 9) / 4;
  const boxY = 30;
  const boxH = 14;

  const boxes = [
    { label: 'TOTAL PROJECTED PAYROLL', value: formatINR(totalPayroll), color: [15, 23, 42] },
    { label: 'FULL PRESENT BONUSES (+2 DAYS)', value: `+${formatINR(totalBonus)}`, color: [180, 83, 9] },
    { label: 'QUALIFIED STAFF (0 ABSENCES)', value: `${totalQualified} / ${payrollStats.length} Staff`, color: [4, 120, 87] },
    { label: 'TOTAL OVERTIME DISBURSED', value: `+${formatINR(totalOt)}`, color: [139, 0, 0] }
  ];

  boxes.forEach((b, i) => {
    const x = 14 + i * (boxWidth + 3);
    doc.setFillColor(248, 250, 252);
    doc.rect(x, boxY, boxWidth, boxH, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.rect(x, boxY, boxWidth, boxH, 'S');

    doc.setFontSize(6.5);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(100, 116, 139);
    doc.text(b.label, x + 3, boxY + 5);

    doc.setFontSize(10.5);
    doc.setTextColor(b.color[0], b.color[1], b.color[2]);
    doc.text(b.value, x + 3, boxY + 11);
  });

  // Prepare table data
  const tableRows = payrollStats.map((p, idx) => {
    const bonusText = p.isFullPresentEligible
      ? `YES (+${formatINR(p.fullPresentBonus)})`
      : `Standard (${p.absent} Abs)`;

    return [
      idx + 1,
      p.emp_id || '--',
      p.name || '--',
      `${p.department || 'Operations'}\n(${p.role || 'Staff'})`,
      formatINR(p.baseSalary),
      `${p.present} Present\n${p.absent} Absent`,
      p.otPay > 0 ? `${p.otMinutes}m (+${formatINR(p.otPay)})` : '0m',
      bonusText,
      formatINR(p.netTotalPayout)
    ];
  });

  // Summary Row at bottom
  tableRows.push([
    '',
    'TOTAL',
    `${payrollStats.length} Employees`,
    '',
    formatINR(payrollStats.reduce((sum, p) => sum + (p.baseSalary || 0), 0)),
    '',
    `+${formatINR(totalOt)}`,
    `+${formatINR(totalBonus)} (${totalQualified} qualified)`,
    formatINR(totalPayroll)
  ]);

  autoTable(doc, {
    startY: 48,
    head: [[
      '#',
      'Emp ID',
      'Employee Name',
      'Department / Role',
      'Base Salary',
      'Attendance Summary',
      'Overtime',
      'Full Present Bonus (+2 Days)',
      'Net Total Payout'
    ]],
    body: tableRows,
    theme: 'grid',
    styles: {
      fontSize: 8,
      cellPadding: 2.2,
      textColor: [30, 41, 59],
      valign: 'middle'
    },
    headStyles: {
      fillColor: [139, 0, 0],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      halign: 'left'
    },
    columnStyles: {
      0: { halign: 'center', cellWidth: 10 },
      1: { halign: 'center', cellWidth: 18, fontStyle: 'bold' },
      2: { cellWidth: 42, fontStyle: 'bold' },
      3: { cellWidth: 38 },
      4: { halign: 'right', cellWidth: 26, fontStyle: 'bold' },
      5: { halign: 'center', cellWidth: 32 },
      6: { halign: 'center', cellWidth: 28 },
      7: { halign: 'center', cellWidth: 42, fontStyle: 'bold' },
      8: { halign: 'right', cellWidth: 32, fontStyle: 'bold', textColor: [139, 0, 0] }
    },
    didParseCell: (data) => {
      // Highlight bonus column
      if (data.section === 'body' && data.column.index === 7) {
        const val = String(data.cell.raw);
        if (val.startsWith('YES')) {
          data.cell.styles.fillColor = [254, 243, 199]; // amber-100
          data.cell.styles.textColor = [146, 64, 14]; // amber-800
          data.cell.styles.fontStyle = 'bold';
        }
      }
      // Highlight TOTAL row
      if (data.section === 'body' && data.row.index === tableRows.length - 1) {
        data.cell.styles.fillColor = [241, 245, 249]; // slate-100
        data.cell.styles.fontStyle = 'bold';
        if (data.column.index === 8) {
          data.cell.styles.textColor = [139, 0, 0];
          data.cell.styles.fontSize = 9;
        }
      }
    },
    margin: { left: 14, right: 14 },
    didDrawPage: (data) => {
      // Footer on every page
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.setFont('helvetica', 'normal');
      const footerText = 'Velavan Properties Payroll & HR Management System • Authorized Report';
      doc.text(footerText, 14, pageHeight - 8);
      const pageStr = `Page ${data.pageNumber} of ${doc.internal.getNumberOfPages()}`;
      doc.text(pageStr, pageWidth - 14, pageHeight - 8, { align: 'right' });
    }
  });

  const fileDate = filters.startDate ? `${filters.startDate}_to_${filters.endDate || 'now'}` : new Date().toISOString().slice(0, 10);
  doc.save(`Velavan_Payroll_Report_${fileDate}.pdf`);
};
