    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.text(`Employee achieved 0 Absences and 0 Half-Days! Extra bonus of +${formatINR(stats.fullPresentBonus)} added to net payout.`, 18, policyY + 7.5);
