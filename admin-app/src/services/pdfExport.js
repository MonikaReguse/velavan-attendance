  const rightX = pageWidth - 60;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.text('MONTHLY BASE SALARY', rightX, infoY + 7);

